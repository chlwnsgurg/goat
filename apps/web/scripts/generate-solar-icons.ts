/**
 * Regenerates apps/web/src/components/solar/solar.generated.ts with only the Solar Linear
 * glyphs the icon modules reference as solar.<camelName>.
 *
 * Solar by 480 Design, CC BY 4.0, via @iconify-json/solar. Run after adding a mapping:
 *   node apps/web/scripts/generate-solar-icons.ts
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeModule from "node:module";

const iconsDir = NodePath.resolve(import.meta.dirname, "../src/components/solar");
const outputPath = NodePath.join(iconsDir, "solar.generated.ts");
const require = NodeModule.createRequire(import.meta.url);
const set: {
  icons: Record<string, { body: string }>;
  aliases: Record<string, { parent: string } & Record<string, unknown>>;
} = require("@iconify-json/solar/icons.json");

const sources = NodeFS.readdirSync(iconsDir)
  .filter((file) => /\.tsx?$/.test(file) && file !== "solar.generated.ts")
  .map((file) => NodeFS.readFileSync(NodePath.join(iconsDir, file), "utf8"));
const names = new Set<string>();
for (const source of sources) {
  for (const match of source.matchAll(/(?<![\w/.])solar\.(?!generated\b)([A-Za-z][A-Za-z0-9]*)/g))
    names.add(match[1]!);
}

function kebab(camel: string): string {
  return camel
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])([0-9])/g, "$1-$2")
    .toLowerCase();
}

function resolveBody(name: string): string {
  let key = name + "-linear";
  const alias = set.aliases[key];
  if (alias) {
    if (Object.keys(alias).some((field) => field !== "parent")) {
      throw new Error("Transformed Solar alias is not supported: " + key);
    }
    key = alias.parent;
  }
  const icon = set.icons[key];
  if (!icon) throw new Error("Unknown Solar Linear icon: " + name);
  return icon.body;
}

type Attrs = Record<string, string>;

/** Solar draws a 1.5 stroke; the app uses it slightly bolder (1.75), scaling every stroke alike. */
const STROKE_SCALE = 1.75 / 1.5;

function scaleStroke(width: string): string {
  return String(Math.round(Number(width) * STROKE_SCALE * 1000) / 1000);
}

function parseAttrs(source: string): Attrs {
  const attrs: Attrs = {};
  for (const match of source.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[match[1]!] = match[2]!;
  return attrs;
}

/** Flattens the SVG body into leaf elements with every inherited presentation attribute. */
function toNode(body: string): Array<[string, Attrs]> {
  const nodes: Array<[string, Attrs]> = [];
  const stack: Attrs[] = [{ fill: "none", stroke: "none", "stroke-width": "1" }];
  for (const match of body.matchAll(/<(\/?)([a-z]+)([^>]*?)(\/?)>/g)) {
    const [, closing, tag, rawAttrs, selfClosing] = match;
    if (closing) {
      if (tag === "g") stack.pop();
      continue;
    }
    const attrs = parseAttrs(rawAttrs!);
    if (tag === "g") {
      stack.push({ ...stack.at(-1), ...attrs });
      continue;
    }
    if (!selfClosing) throw new Error("Unexpected element with children: " + tag);
    const merged: Attrs = { ...stack.at(-1), ...attrs };
    // The wrapper's <svg> paints fill="none" stroke="currentColor"; keep only overrides so a
    // fill-current class on the svg still reaches outline glyphs such as the stop square.
    if (merged.fill === "none") delete merged.fill;
    if (merged.stroke === "currentColor") delete merged.stroke;
    if (merged.stroke === "none") delete merged["stroke-width"];
    else merged["stroke-width"] = scaleStroke(merged["stroke-width"]!);
    nodes.push([tag!, merged]);
  }
  return nodes;
}

const lines = [
  "// Generated by apps/web/scripts/generate-solar-icons.ts. Do not edit.",
  "// Solar icon set by 480 Design, CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).",
  'import type { IconNode } from "./iconNode";',
  "",
];
for (const name of [...names].toSorted()) {
  lines.push(
    "export const " +
      name +
      ": IconNode = " +
      JSON.stringify(toNode(resolveBody(kebab(name)))) +
      ";",
  );
}
NodeFS.writeFileSync(outputPath, lines.join("\n") + "\n");
console.log(
  "Wrote " + names.size + " Solar icons to " + NodePath.relative(process.cwd(), outputPath),
);
